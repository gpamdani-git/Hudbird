import os
import glob
import json

blocks_dir = "packages/marketing/src/blocks"
output_file = "apps/docs/src/data/blocks.ts"

templates = ["AiStartup", "Ecommerce", "Fintech", "HybridStartup", "ModernApp", "SaaS", "Agency"]

categories = {}

for template in templates:
    template_dir = os.path.join(blocks_dir, template)
    if not os.path.exists(template_dir):
        continue
    
    for category in os.listdir(template_dir):
        cat_dir = os.path.join(template_dir, category)
        if not os.path.isdir(cat_dir) or category == "components":
            continue
        
        # e.g., category = "Hero"
        if category not in categories:
            categories[category] = []
            
        # Find the main file, usually {Template}{Category}.tsx
        main_file = os.path.join(cat_dir, f"{template}{category}.tsx")
        if not os.path.exists(main_file):
            # Try to find any tsx file that isn't empty
            files = glob.glob(os.path.join(cat_dir, "*.tsx"))
            if files:
                main_file = files[0]
            else:
                continue
        
        component_name = os.path.basename(main_file).replace(".tsx", "")
        import_path = f"../../../../packages/marketing/src/blocks/{template}/{category}/{os.path.basename(main_file)}"
        
        categories[category].append({
            "template": template,
            "componentName": component_name,
            "importPath": import_path
        })

# Generate the TS file
ts_code = "// Auto-generated by script\n"
ts_code += "import React, { lazy } from 'react';\n\n"

for category, blocks in categories.items():
    for block in blocks:
        ts_code += f"import {block['componentName']}Raw from '{block['importPath']}?raw';\n"
        ts_code += f"const {block['componentName']} = lazy(() => import('@hudbird/marketing').then(m => ({{ default: m.{block['componentName']} }})));\n"

ts_code += "\nexport const BLOCKS_DATA = {\n"
for category, blocks in categories.items():
    ts_code += f"  '{category}': [\n"
    for block in blocks:
        ts_code += f"    {{\n"
        ts_code += f"      template: '{block['template']}',\n"
        ts_code += f"      name: '{block['componentName']}',\n"
        ts_code += f"      component: {block['componentName']},\n"
        ts_code += f"      code: {block['componentName']}Raw,\n"
        ts_code += f"    }},\n"
    ts_code += "  ],\n"
ts_code += "};\n"

with open(output_file, "w") as f:
    f.write(ts_code)

print("Generated blocks data successfully.")
