export type SystemFolder =
  "inbox" | "starred" | "snoozed" | "sent" | "drafts" | "scheduled" | "spam" | "trash" | "archive";

/** Custom folder ids are prefixed with `f:` so they never collide with system folders. */
export type MailFolder = SystemFolder | `f:${string}`;

export type MailLabel = "personal" | "work" | "promotions" | "social" | "updates" | "finance";

export type AppView = "mail" | "ai" | "calendar" | "folders" | "settings" | "support" | "upgrade";

export type ListFilter = "all" | "unread" | "read" | "starred" | "attachments";

export interface Attachment {
  id?: string;
  name: string;
  size: string;
  type: "image" | "video" | "document";
  url: string;
  /** True when the attachment was generated by the AI image simulator. */
  aiGenerated?: boolean;
}

export interface ThreadItem {
  id: string;
  senderName: string;
  senderEmail: string;
  date: string;
  subject: string;
  body: string;
  avatar?: string;
}

export interface Mail {
  id: string;
  senderName: string;
  senderEmail: string;
  to?: string;
  subject: string;
  preview: string;
  body: string;
  date: string;
  folder: MailFolder;
  labels: MailLabel[];
  isRead: boolean;
  isStarred: boolean;
  isSnoozed?: boolean;
  isImportant?: boolean;
  attachments?: Attachment[];
  thread?: ThreadItem[];
  threadCount?: number;
  /** Pre-computed AI summary bullets for the detail view. */
  aiSummary?: string[];
  aiPriority?: "high" | "medium" | "low";
}

export interface CustomFolder {
  id: `f:${string}`;
  name: string;
  color: string;
}

export type ComposeMode = "new" | "reply" | "forward" | "draft";

export interface ComposeDraft {
  id: string;
  mode: ComposeMode;
  to: string;
  cc: string;
  subject: string;
  body: string;
  attachments: Attachment[];
  status: "idle" | "sending" | "sent" | "failed";
  /** Optional id of the draft mail being edited, so we can replace it on save. */
  sourceDraftId?: string;
  scheduledFor?: string;
}

export interface CalendarEvent {
  id: string;
  title: string;
  date: string; // yyyy-mm-dd
  start: string; // HH:mm
  end: string; // HH:mm
  color: "blue" | "violet" | "emerald" | "amber" | "rose";
  location?: string;
  attendees?: string[];
  fromMailId?: string;
  aiSuggested?: boolean;
}

export interface AppNotification {
  id: string;
  title: string;
  body: string;
  time: string;
  type: "mail" | "ai" | "calendar" | "system";
  read: boolean;
}

export interface Toast {
  id: string;
  message: string;
  tone?: "default" | "success" | "error" | "ai";
  action?: { label: string; onClick: () => void };
}
