export const PREBUILT_47_TEMPLATES: PrebuiltTemplateMeta[] = RAW_PREBUILT_47_TEMPLATES.map(
  (tpl, idx) => ({
    ...tpl,
    numId: idx + 1,
    name: tpl.title,
  })
);

export function getPrebuiltTemplateMeta(slug: string): PrebuiltTemplateMeta | undefined {
  const clean = slug.replace(/^\/+|\/+$/g, "").replace(/^demos\//, "");
  return PREBUILT_47_TEMPLATES.find((t) => t.slug === clean || t.id === clean);
}

/**
 * Dynamically synthesize a full NicheConfig for ANY of the 47 Pre-Built Templates
 * so every single template route (/demos/:nicheSlug and /demos/:nicheSlug/*) renders
 * with its own brand title, hero headline, accent color, polarity, and 29+ inner pages.
 */
export function buildNicheConfigFromPrebuilt(meta: PrebuiltTemplateMeta): NicheConfig {
  const base: NicheConfig =
    meta.archetype === "ai"
      ? aiCopilotNiche
      : meta.archetype === "fintech" || meta.archetype === "proptech"
        ? fintechProtocolNiche
        : meta.archetype === "cyber"
          ? cyberShieldNiche
          : meta.archetype === "wellness"
            ? alunaraWellnessNiche
            : digitalAgencyNiche;

  return {
    ...base,
    id: meta.id,
    name: `HudbirdUI ${meta.title}`,
    slug: meta.slug,
    tagline: meta.tagline,
    category: meta.category,
    theme: {
      ...base.theme,
      brandPrimary: meta.accent,
      brandAccent: meta.accent,
      mode: meta.mode,
    },
    innerPages: createNicheInnerPages(meta.slug, `HudbirdUI ${meta.title}`),
    sections: {
      ...base.sections,
      navbar: {
        ...base.sections.navbar,
        brandName: "HudbirdUI",
        brandTag: meta.title,
        primaryCta: {
          label: meta.primaryCtaLabel,
          href: `/demos/${meta.slug}/contact`,
        },
      },
      hero: {
        ...base.sections.hero,
        taglineBadge: {
          label: meta.tagline,
          pulsing: true,
        },
        headline: {
          preText: meta.heroPreText,
          serifAccentWord: meta.heroAccentWord,
          accentWord: meta.heroAccentWord,
          postText: meta.heroPostText,
        } as NicheConfig["sections"]["hero"]["headline"],
        description: meta.heroDescription,
        primaryCta: {
          label: meta.primaryCtaLabel,
          href: `/demos/${meta.slug}/contact`,
        },
        secondaryCta: {
          label: "Explore Architecture",
          href: `/demos/${meta.slug}/services`,
        },
      },
      footer: {
        ...base.sections.footer,
        primaryCta: {
          label: meta.primaryCtaLabel,
          href: `/demos/${meta.slug}/contact`,
        },
      },
    },
  };
}
